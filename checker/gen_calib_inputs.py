def main():
    with open(os.path.join(BASE, "calib-labels.json")) as f:
        labels = json.load(f)
    tests = []
    rewrites = {}
    for i, rec in enumerate(labels, 1):
        sf, nm, predicted, basis = PROMPTS[rec["index"]]
        tests.append({
            "test": i, "layer": rec["layer"], "source": rec["source"],
            "index": rec["index"], "label": rec["label"],
            "should_fire": sf, "near_miss": nm,
            "predicted": predicted, "basis": basis,
        })
        r = REWRITES[rec["index"]]
        rewrites[str(i)] = {"sf1": r[0], "sf2": r[1]}
    with open(os.path.join(BASE, "calibration-prompts-in.json"), "w") as f:
        json.dump({"tests": tests}, f, indent=1)
    with open(os.path.join(BASE, "calibration-rewrites-in.json"), "w") as f:
        json.dump(rewrites, f, indent=1)
    truth = {"14719": "word-form", "5158": "word-form", "8743": "word-form",
             "1029": "word-form", "2580": "register", "3580": "register",
             "5072": "register", "8630": "register", "7623": "register",
             "18": "displaced-theme", "2081": "document-bound",
             "2625": "document-bound", "3349": "document-bound",
             "6515": "document-bound", "3070": "unresolved",
             "7196": "unresolved", "14520": "unresolved"}
    with open(os.path.join(BASE, "mechanism-truth.json"), "w") as f:
        json.dump(truth, f, indent=1)
    print(f"wrote {len(tests)} tests, {len(rewrites)} rewrite pairs, mechanism truth for {len(truth)}")

